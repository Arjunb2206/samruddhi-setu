let currentLang = localStorage.getItem("agrisetu_lang") || "en";

function t(key, fallback) {
  if (translations[currentLang] && translations[currentLang][key]) {
    return translations[currentLang][key];
  }
  if (translations.en && translations.en[key]) {
    return translations.en[key];
  }
  return fallback !== undefined ? fallback : key;
}

function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem("agrisetu_lang", lang);
    updateDOMTranslations();
    document.querySelectorAll(".lang-selector-select").forEach(el => el.value = lang);
    window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
  }
}

function getLanguage() {
  return currentLang;
}

function updateDOMTranslations() {
  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.getAttribute("data-i18n");
    if (key) {
      const translated = t(key);
      if (element.tagName === "INPUT" || element.tagName === "TEXTAREA") {
        if (element.hasAttribute("placeholder")) {
          element.placeholder = translated;
        }
      } else {
        element.innerHTML = translated;
      }
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    const key = element.getAttribute("data-i18n-placeholder");
    if (key) {
      element.placeholder = t(key);
    }
  });

  document.querySelectorAll("[data-i18n-title]").forEach(element => {
    const key = element.getAttribute("data-i18n-title");
    if (key) {
      element.title = t(key);
    }
  });
}

// Auto-run on DOMContentLoaded
document.addEventListener("DOMContentLoaded", () => {
  updateDOMTranslations();
  // Keep every language dropdown on the page (including shell/dashboard ones
  // rendered dynamically) in sync with whatever language is currently active.
  document.querySelectorAll(".lang-selector-select").forEach(el => el.value = currentLang);
});

window.i18n = { t, setLanguage, getLanguage, updateDOMTranslations };
